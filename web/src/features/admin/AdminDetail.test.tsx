import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { focusManager, QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { beforeEach, expect, it, vi } from "vitest";
import { ApiError } from "../../api/client";
import { adminApi } from "./api";
import { AdminDetail } from "./AdminDetail";
vi.mock("./api", () => ({ adminApi: { detail: vi.fn(), session: vi.fn(), act: vi.fn(), reauth: vi.fn() } }));
beforeEach(() => { vi.resetAllMocks(); vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} }); vi.stubGlobal("matchMedia", vi.fn(() => ({ matches: false, addListener: vi.fn(), removeListener: vi.fn(), addEventListener: vi.fn(), removeEventListener: vi.fn() }))); });
const user = { id: "u1", nickname: "棋友", email: "full@example.test", role: "user", status: "active", version: 3, sessionCount: 2 };
function show() { const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } }); render(<QueryClientProvider client={client}><AdminDetail module="users" row={user} onClose={vi.fn()} /></QueryClientProvider>); }
it("preserves the reason through expired reauthentication and a failed password", async () => {
  vi.mocked(adminApi.detail).mockResolvedValue(user);
  vi.mocked(adminApi.act).mockRejectedValueOnce(new ApiError("REAUTH_REQUIRED")).mockResolvedValueOnce({ requestId: "x", version: 4, status: "banned" });
  vi.mocked(adminApi.reauth).mockRejectedValueOnce(new ApiError("INVALID_CREDENTIALS")).mockResolvedValueOnce({ expiresAt: 123 });
  show(); fireEvent.click(await screen.findByRole("button", { name: "封禁账号" }));
  fireEvent.change(screen.getByLabelText("操作原因"), { target: { value: "异常行为" } });
  fireEvent.click(screen.getByRole("button", { name: "确认封禁账号" }));
  fireEvent.change(await screen.findByLabelText("确认管理员密码"), { target: { value: "wrong" } });
  fireEvent.click(screen.getByRole("button", { name: "确认身份并继续" }));
  await screen.findByText("密码不正确，请重新输入。");
  expect(screen.getByLabelText("操作原因")).toHaveValue("异常行为");
  fireEvent.change(screen.getByLabelText("确认管理员密码"), { target: { value: "correct" } });
  fireEvent.click(screen.getByRole("button", { name: "确认身份并继续" }));
  await waitFor(() => expect(adminApi.act).toHaveBeenCalledTimes(2));
  const first = vi.mocked(adminApi.act).mock.calls[0][3], second = vi.mocked(adminApi.act).mock.calls[1][3];
  expect(second).toEqual(first); expect(second.reason).toBe("异常行为"); expect(second.version).toBe(3);
});
it("requires a reason before issuing an action", async () => {
  vi.mocked(adminApi.detail).mockResolvedValue(user); show();
  fireEvent.click(await screen.findByRole("button", { name: "封禁账号" }));
  fireEvent.click(screen.getByRole("button", { name: "确认封禁账号" }));
  expect(screen.getByRole("alert")).toHaveTextContent("请填写操作原因"); expect(adminApi.act).not.toHaveBeenCalled();
});
it("requires a fresh decision when the object's version changes", async () => {
  vi.mocked(adminApi.detail).mockResolvedValueOnce(user).mockResolvedValueOnce({ ...user, status: "banned", version: 4 });
  vi.mocked(adminApi.act).mockRejectedValueOnce(new ApiError("VERSION_CONFLICT")); show();
  fireEvent.click(await screen.findByRole("button", { name: "封禁账号" }));
  fireEvent.change(screen.getByLabelText("操作原因"), { target: { value: "需要核查" } });
  fireEvent.click(screen.getByRole("button", { name: "确认封禁账号" }));
  await screen.findByText("对象状态已变化，请刷新详情后重新操作。");
  fireEvent.click(screen.getByRole("button", { name: "刷新详情" }));
  await screen.findByText("对象状态已变化，请返回重新选择操作。");
  expect(screen.getByLabelText("操作原因")).toHaveValue("需要核查");
  expect(screen.getByRole("button", { name: "确认封禁账号" })).toBeDisabled();
});
it("keeps the decision version through a background refresh and renews it only after explicit conflict refresh", async () => {
  const refreshed = { ...user, version: 4, nickname: "更新的棋友" };
  vi.mocked(adminApi.detail).mockResolvedValueOnce(user).mockResolvedValue(refreshed);
  vi.mocked(adminApi.act).mockRejectedValueOnce(new ApiError("VERSION_CONFLICT")).mockResolvedValueOnce({ requestId: "x", version: 5, status: "banned" });
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  render(<QueryClientProvider client={client}><AdminDetail module="users" row={user} onClose={vi.fn()} /></QueryClientProvider>);
  fireEvent.click(await screen.findByRole("button", { name: "封禁账号" }));
  fireEvent.change(screen.getByLabelText("操作原因"), { target: { value: "需要核查" } });
  act(() => { focusManager.setFocused(false); focusManager.setFocused(true); });
  await screen.findByText("更新的棋友");
  fireEvent.click(screen.getByRole("button", { name: "确认封禁账号" }));
  await screen.findByText("对象状态已变化，请刷新详情后重新操作。");
  const first = vi.mocked(adminApi.act).mock.calls[0][3];
  expect(first.version).toBe(3);
  fireEvent.click(screen.getByRole("button", { name: "刷新详情" }));
  await waitFor(() => expect(screen.queryByText("对象状态已变化，请刷新详情后重新操作。")).not.toBeInTheDocument());
  expect(screen.getByLabelText("操作原因")).toHaveValue("需要核查");
  const confirm = await screen.findByRole("button", { name: "确认封禁账号" });
  await waitFor(() => expect(confirm).toBeEnabled());
  fireEvent.click(confirm);
  await waitFor(() => expect(adminApi.act).toHaveBeenCalledTimes(2));
  const second = vi.mocked(adminApi.act).mock.calls[1][3];
  expect(second.version).toBe(4); expect(second.reason).toBe(first.reason); expect(second.requestId).not.toBe(first.requestId);
});
it("reports a task that failed during a pause race without claiming it was paused", async () => {
  const task = { id: "t1", status: "running", version: 1 };
  vi.mocked(adminApi.detail).mockResolvedValue(task);
  vi.mocked(adminApi.act).mockResolvedValue({ requestId: "x", version: 1, status: "failed" });
  const done = vi.fn(); const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  render(<QueryClientProvider client={client}><AdminDetail module="tasks" row={task} onClose={vi.fn()} onDone={done} /></QueryClientProvider>);
  fireEvent.click(await screen.findByRole("button", { name: "暂停任务" }));
  fireEvent.change(screen.getByLabelText("操作原因"), { target: { value: "异常任务" } });
  fireEvent.click(screen.getByRole("button", { name: "确认暂停任务" }));
  await waitFor(() => expect(done).toHaveBeenCalledWith("任务已失败，未暂停。"));
});
it("refreshes a conflicting session without discarding the reason", async () => {
  const now = Date.now();
  const session = { id: "s1", userId: "u1", expiresAt: now + 60000, lastSeen: now, revokedAt: 0, version: 1 };
  vi.mocked(adminApi.act).mockRejectedValueOnce(new ApiError("VERSION_CONFLICT")).mockResolvedValueOnce({ requestId: "x", version: 3, status: "revoked" });
  vi.mocked(adminApi.session).mockResolvedValue({ ...session, version: 2 });
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  render(<QueryClientProvider client={client}><AdminDetail module="sessions" row={session} onClose={vi.fn()} /></QueryClientProvider>);
  fireEvent.click(screen.getByRole("button", { name: "撤销会话" }));
  fireEvent.change(screen.getByLabelText("操作原因"), { target: { value: "需要撤销" } });
  fireEvent.click(screen.getByRole("button", { name: "确认撤销会话" }));
  await screen.findByText("对象状态已变化，请刷新详情后重新操作。");
  fireEvent.click(screen.getByRole("button", { name: "刷新详情" }));
  await waitFor(() => expect(adminApi.session).toHaveBeenCalledWith("u1", "s1"));
  await waitFor(() => expect(screen.queryByText("对象状态已变化，请刷新详情后重新操作。")).not.toBeInTheDocument());
  expect(screen.getByLabelText("操作原因")).toHaveValue("需要撤销");
  fireEvent.click(screen.getByRole("button", { name: "确认撤销会话" }));
  await waitFor(() => expect(adminApi.act).toHaveBeenCalledTimes(2));
  expect(vi.mocked(adminApi.act).mock.calls[1][3].version).toBe(2);
});
